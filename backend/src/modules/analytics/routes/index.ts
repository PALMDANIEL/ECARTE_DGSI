import { Router } from 'express';
import { AnalyticsController } from '../controllers/analytics.controller';
import { AnalyticsService } from '../services/analytics.service';
import { ScanRepository } from '../../scans/repositories/scan.repository';
import { UserRepository } from '../../users/repositories/user.repository';
import { CompanyRepository } from '../../companies/repositories/company.repository';
import { BusinessCardRepository } from '../../business-cards/repositories/card.repository';
import { authenticate } from '../../../middlewares/auth.middleware';
const router = Router();
const scanRepo = new ScanRepository();
const userRepo = new UserRepository();
const companyRepo = new CompanyRepository();
const cardRepo = new BusinessCardRepository();
const service = new AnalyticsService(scanRepo, userRepo, companyRepo, cardRepo);
const controller = new AnalyticsController(service);
router.use(authenticate);
router.get('/stats', controller.getDashboardStats.bind(controller));
router.get('/statistics', controller.getStatistics.bind(controller));
export { router as analyticsRouter };
