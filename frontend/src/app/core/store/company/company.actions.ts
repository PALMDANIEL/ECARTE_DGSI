import { createAction, props } from '@ngrx/store';
import { Company } from '../../models/company.model';
export const loadCompanies = createAction('[Company] Load Companies');
export const loadCompaniesSuccess = createAction('[Company] Load Companies Success', props<{ companies: Company[] }>());
export const loadCompaniesFailure = createAction('[Company] Load Companies Failure', props<{ error: string }>());
export const createCompany = createAction('[Company] Create Company', props<{ company: any }>());
export const createCompanySuccess = createAction('[Company] Create Company Success', props<{ company: Company }>());
export const createCompanyFailure = createAction('[Company] Create Company Failure', props<{ error: string }>());
export const updateCompany = createAction('[Company] Update Company', props<{ id: string; company: any }>());
export const updateCompanySuccess = createAction('[Company] Update Company Success', props<{ company: Company }>());
export const updateCompanyFailure = createAction('[Company] Update Company Failure', props<{ error: string }>());
export const deleteCompany = createAction('[Company] Delete Company', props<{ id: string }>());
export const deleteCompanySuccess = createAction('[Company] Delete Company Success', props<{ id: string }>());
export const deleteCompanyFailure = createAction('[Company] Delete Company Failure', props<{ error: string }>());
